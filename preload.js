'use strict';

const { contextBridge, ipcRenderer, webFrame } = require('electron');

const call = (channel, ...args) => ipcRenderer.invoke(channel, ...args);

contextBridge.exposeInMainWorld('api', {
  setZoom: (factor) => { const f = Number(factor); if (f >= 0.5 && f <= 2) webFrame.setZoomFactor(f); },
  getConfig: () => call('config:get'),
  saveConfig: (data) => call('config:save', data),
  setTheme: (theme) => call('config:setTheme', theme),
  lastGame: () => call('games:last'),
  searchGames: (query) => call('games:search', query),
  loadGame: (appid) => call('game:load', appid),
  listDlcs: (data) => call('dlc:list', data),
  combineClasses: (data) => call('class:combine', data),
  voteOrigins: (data) => call('origin:vote', data),
  setOrigins: (data) => call('origin:setMany', data),
  setOrigin: (data) => call('origin:set', data),
  listTrash: () => call('trash:list'),
  restoreTrash: (data) => call('trash:restore', data),
  emptyTrash: () => call('trash:empty'),
  exportData: () => call('data:export'),
  importData: () => call('data:import'),
  dataInfo: () => call('data:info'),
  chooseDataDir: () => call('data:chooseDir'),
  resetDataDir: () => call('data:resetDir'),
  relaunch: () => call('app:relaunch'),
  exportMissing: (data) => call('export:missing', data),
  testConnections: () => call('diag:test'),
  saveDiagReport: () => call('diag:report'),
  setNote: (data) => call('notes:set', data),
  setClassification: (data) => call('class:set', data),
  loadGuides: (data) => call('guides:load', data),
  findMods: (data) => call('mods:find', data),
  findMap: (data) => call('map:find', data),
  gameCover: (appid) => ipcRenderer.invoke('game:cover', appid),
  onGuideProgress: (cb) => { const fn = (_e, evt) => cb(evt); ipcRenderer.on('guides:progress', fn); return () => ipcRenderer.removeListener('guides:progress', fn); },
  getSettings: () => call('settings:get'),
  sanitizeSettings: (data) => call('settings:sanitize', data),
  resetSettings: () => call('settings:reset'),
  saveSettings: (data) => call('settings:save', data),
  listCache: () => call('cache:list'),
  deleteCache: (scope) => call('cache:delete', scope),
  radioNow: () => call('radio:now'),
  getChangelog: () => call('app:changelog'),
  getUpdate: () => call('update:state'),
  checkUpdate: () => call('update:check'),
  applyUpdate: () => call('update:apply'),
  onUpdateState: (cb) => { const fn = (_e, st) => cb(st); ipcRenderer.on('update:state', fn); return () => ipcRenderer.removeListener('update:state', fn); },
  cancelGuides: () => call('guides:cancel'),
  translateTexts: (data) => call('translate:texts', data),
  loadGuidesFallback: (data) => call('guides:fallback', data),
  getTime: (data) => call('time:get', data),
  fetchImage: (urls) => call('image:fetch', urls),
  openExternal: (url) => call('shell:open', url),
});
